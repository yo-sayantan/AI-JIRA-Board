#!/usr/bin/env node
// Writes help/help-data.js — the data the help pages show, as a plain script the browser can load from disk.
//
// The help pages are meant to open straight from the file system (file://), before anything is deployed.
// A page opened that way cannot fetch() a JSON file, but it can load a <script src>. So every build copies
// what the pages need into one script:
//   • ai-intern/models.json         → the local-model tables (Ollama tags, GGUF downloads)
//   • ai-intern/cursor-prices.json  → the cloud price table
//   • ai-intern/cloud-models.json   → which cloud models Settings offers, and the costly line
//   • docs/*.md                     → the developer-doc viewer
// When the pages are served by the board they read the live files instead; this copy is the offline view.
//
//   node scripts/build-help-data.mjs           write it (npm run build does this first)
//   node scripts/build-help-data.mjs --check   exit 1 if it is out of date (the tests run this)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'help', 'help-data.js')

function json(rel) {
  return JSON.parse(readFileSync(join(ROOT, rel), 'utf8'))
}

export function buildHelpData() {
  const docsDir = join(ROOT, 'docs')
  const docs = {}
  for (const name of readdirSync(docsDir).filter((n) => n.endsWith('.md')).sort()) {
    docs[name] = readFileSync(join(docsDir, name), 'utf8')
  }
  const data = {
    models: json('ai-intern/models.json'),
    cursorPrices: json('ai-intern/cursor-prices.json'),
    cloudModels: json('ai-intern/cloud-models.json'),
    docs,
  }
  // One key per line keeps a diff of this file readable (which source changed?).
  const body = Object.entries(data)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`)
    .join(',\n')
  return (
    '// AUTO-GENERATED by scripts/build-help-data.mjs — do not edit by hand.\n' +
    '// A copy of ai-intern/models.json, ai-intern/cursor-prices.json, ai-intern/cloud-models.json and docs/*.md,\n' +
    '// so the help pages work when opened straight from disk. Every `npm run build` refreshes it\n' +
    '// (or run: node scripts/build-help-data.mjs).\n' +
    'window.JB_HELP_DATA = {\n' +
    body +
    '\n};\n'
  )
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const next = buildHelpData()
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (cur !== next) {
      console.error('help/help-data.js is out of date — run: node scripts/build-help-data.mjs (npm run build does it too)')
      process.exit(1)
    }
    console.log('help/help-data.js is up to date')
  } else {
    writeFileSync(OUT, next)
    console.log(`wrote help/help-data.js (${Math.round(next.length / 1024)} KB)`)
  }
}
